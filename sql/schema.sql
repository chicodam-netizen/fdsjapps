-- =====================================================================
-- Sistema QRZ - Estrutura do banco (Supabase / PostgreSQL)
-- Usado para criar o banco de cada nova instância (uma por empresa).
--
-- Segurança: RLS ligado e SEM políticas => a API pública (chave anon /
-- publishable) não acessa as tabelas. O app Streamlit roda no servidor e
-- deve usar a chave service_role / secret (que ignora o RLS) em
-- [connections.supabase] SUPABASE_KEY.
-- =====================================================================

-- Atualiza automaticamente a coluna updated_at
create or replace function public.update_updated_at_column()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

-- ---------------------------------------------------------------------
-- Usuários do sistema (autenticação própria: PBKDF2 + salt)
-- ---------------------------------------------------------------------
create table if not exists public.usuarios (
    id                 integer generated by default as identity primary key,
    email              varchar not null unique,
    senha_hash         varchar not null,
    salt               varchar not null,
    nome_completo      varchar not null,
    two_factor_secret  varchar,
    two_factor_enabled boolean default false,
    created_at         timestamptz default now(),
    updated_at         timestamptz default now(),
    last_login         timestamptz,
    reset_code         varchar,
    reset_expires      timestamptz,
    is_admin           boolean default false,
    auth_user_id       uuid unique
);

drop trigger if exists update_usuarios_updated_at on public.usuarios;
create trigger update_usuarios_updated_at
    before update on public.usuarios
    for each row execute function public.update_updated_at_column();

-- ---------------------------------------------------------------------
-- Backlog de tarefas
-- ---------------------------------------------------------------------
create table if not exists public.tarefasqrz (
    id_registro                 integer generated by default as identity primary key,
    tarefa_product_backlog      text,
    setor_grooming_detalhamento text,
    origem_nao_conformidade     text,
    resultado_rei               numeric,
    execucao_rei                numeric,
    investimento_rei            numeric,
    matriz_rei                  numeric,
    gravidade_gut               numeric,
    urgencia_gut                numeric,
    tendencia_gut               numeric,
    matriz_gut                  numeric,
    soma_gut_rei                numeric,
    detalhamento_acoes          text,
    percentual_ok               numeric,
    pessoa_responsavel          text,
    data_previsao_conclusao     date,
    data_conclusao              date,
    status                      text,
    data_criacao                timestamptz default now(),
    user_id                     integer,
    ultimo_usuario_edicao       varchar,
    data_ultima_edicao          timestamptz
);

create index if not exists tarefasqrz_user_id_idx on public.tarefasqrz (user_id);

-- ---------------------------------------------------------------------
-- Row Level Security
-- O app usa autenticação própria (não usa Supabase Auth), então o banco
-- não sabe qual usuário está logado. Liberar acesso para anon/authenticated
-- equivaleria a deixar as tabelas públicas. Por isso:
--   * somente o papel service_role (chave secreta, usada no servidor) acessa;
--   * anon e authenticated ficam sem políticas e sem privilégios.
-- ---------------------------------------------------------------------
alter table public.usuarios   enable row level security;
alter table public.tarefasqrz enable row level security;

drop policy if exists "usuarios_acesso_servidor" on public.usuarios;
create policy "usuarios_acesso_servidor" on public.usuarios
    for all to service_role using (true) with check (true);

drop policy if exists "tarefasqrz_acesso_servidor" on public.tarefasqrz;
create policy "tarefasqrz_acesso_servidor" on public.tarefasqrz
    for all to service_role using (true) with check (true);

revoke all on public.usuarios, public.tarefasqrz from anon, authenticated;
